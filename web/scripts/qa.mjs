import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
import { writeFile, mkdir } from 'node:fs/promises'

const base = process.env.DEMO_URL || 'http://127.0.0.1:48740'
const output = new URL('../../qa/ui-polish/', import.meta.url).pathname
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ executablePath: process.env.CHROME_BIN || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] })
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
const checks = []
const check = (name, condition) => { assert.ok(condition, name); checks.push(name) }
const shot = name => page.screenshot({ path: `${output}${name}`, fullPage: false })
const noOverflow = () => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)
const ready = () => page.evaluate(() => document.fonts.ready)
const dbBooks = () => page.evaluate(() => new Promise((resolve, reject) => {
  const open = indexedDB.open('anthreed-v1', 1)
  open.onsuccess = () => { const db = open.result; const request = db.transaction('books').objectStore('books').getAll(); request.onsuccess = () => { resolve(request.result.map(({ data, ...book }) => ({ ...book, dataBytes: data.byteLength }))); db.close() }; request.onerror = reject }
  open.onerror = reject
}))
try {
  await page.goto(base, { waitUntil: 'networkidle' }); await ready()
  await page.locator('.article-card').first().waitFor()
  const feed = await (await page.request.get(`${base}/data/articles.json`)).json()
  check('Selection mode is disclosed', ['deepseek', 'local_fallback'].includes(feed.selection_mode))
  check('Feed contains one winner per cluster', new Set(feed.articles.map(article => article.cluster_id)).size === feed.articles.length)
  const rendered = await page.locator('[data-cluster-id]').evaluateAll(nodes => nodes.map(node => node.dataset.clusterId))
  check('Rendered cards have no duplicate event IDs', new Set(rendered).size === rendered.length && rendered.length === feed.articles.length)
  check('Playfair Display Italic loads on text-only brand', await page.locator('.brand').evaluate(node => document.fonts.check('italic 600 22px "Playfair Display"') && getComputedStyle(node).fontFamily.startsWith('"Playfair Display"') && getComputedStyle(node).fontStyle === 'italic' && node.textContent === 'Anthreed' && !node.querySelector('svg')))
  check('No subscription toolbar or heading book illustration remains', await page.locator('.feed-toolbar, .heading-illustration').count() === 0 && !(await page.locator('body').innerText()).includes('我的订阅'))
  check('Page title uses Newsreader reading stack', await page.locator('h1').evaluate(node => { const family = getComputedStyle(node).fontFamily; return family.includes('Newsreader') && !family.startsWith('"Playfair Display"') && getComputedStyle(node).fontStyle !== 'italic' }))
  check('Article card titles use Newsreader, not Playfair', await page.locator('.article-link h2').first().evaluate(node => { const family = getComputedStyle(node).fontFamily; return family.includes('Newsreader') && !family.includes('Playfair Display') }))
  check('Demo contains at least two substantial inline bodies', feed.articles.filter(a => a.content?.trim().length > 500 && a.content.includes('\n\n')).length >= 2)
  check('Mobile subscription page has no horizontal overflow', await noOverflow())
  await shot('01-subscribe.png')
  for (const source of ['归藏', '乔木', 'AIHOT']) {
    await page.getByRole('button', { name: source, exact: true }).click()
    const expected = Object.entries({ guizang: '归藏', qiaomu: '乔木', aihot: 'AIHOT' }).find(([, label]) => label === source)[0]
    check(`${source} filter shows only chosen articles from that source`, await page.locator('.article-card').count() === feed.articles.filter(article => article.source === expected).length)
  }
  await page.getByRole('button', { name: '全部', exact: true }).click()
  await page.locator('.article-card').first().getByRole('button', { name: '收藏文章' }).click()
  await page.getByRole('button', { name: '只看收藏' }).click()
  check('Saved-article filter works', await page.locator('.article-card').count() === 1)
  await page.getByRole('button', { name: '只看收藏' }).click()
  const bodyArticle = feed.articles.find(a => a.source === 'qiaomu' && a.content?.trim().length > 1000 && a.title.length < 45) || feed.articles.find(a => a.content?.trim().length > 500)
  await page.locator(`.article-link[href="#article/${bodyArticle.id}"]`).click()
  await page.locator('.reading-content').waitFor()
  check('Full article paragraphs render inline', await page.locator('.reading-body').innerText() === bodyArticle.content.trim() && await page.locator('.reading-body p').count() >= 2)
  check('Full body is not represented as a source summary', await page.locator('.summary-notice, .body-empty').count() === 0)
  check('No prominent original article CTA remains', await page.locator('.original-link').count() === 0 && await page.getByRole('link', { name: /阅读原文|继续探索/ }).count() === 0)
  check('Reader title uses Newsreader reading stack', await page.locator('.reading-content h1').evaluate(node => { const family = getComputedStyle(node).fontFamily; return family.includes('Newsreader') && !family.startsWith('"Playfair Display"') && getComputedStyle(node).fontStyle !== 'italic' }))
  check('Mobile article body has no horizontal overflow', await noOverflow())
  await shot('02-article.png')
  await page.locator('.reading-body').evaluate(node => node.scrollIntoView({ block: 'start' }))
  await shot('02-article-body.png')
  await page.evaluate(() => scrollTo(0, 0))
  await page.locator('.reading-body p').first().evaluate(node => { const range = document.createRange(); range.selectNodeContents(node); const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range); node.dispatchEvent(new PointerEvent('pointerup', { bubbles: true })) })
  await page.getByRole('button', { name: '摘录选中文字', exact: true }).click()
  await page.getByRole('status').waitFor()
  await page.getByRole('button', { name: /调整字号/ }).click()
  check('Reader font size changes', await page.locator('.reading-body').evaluate(node => getComputedStyle(node).fontSize) === '20px')
  await page.getByRole('button', { name: '订阅', exact: true }).click()
  await page.getByRole('link', { name: '书架', exact: true }).click()
  await page.getByRole('heading', { name: '把一本书，带到这里。' }).waitFor()
  await shot('03-bookshelf-empty.png')
  await page.getByLabel('选择 EPUB 文件').setInputFiles(new URL('../public/demo.epub', import.meta.url).pathname)
  await page.locator('.book-item').waitFor()
  let stored = await dbBooks()
  check('EPUB file bytes and parsed chapters persist in IndexedDB', stored.length === 1 && stored[0].dataBytes > 0 && stored[0].chapters.length === 3)
  await page.reload({ waitUntil: 'networkidle' }); await ready()
  await page.locator('.book-item').waitFor()
  check('Imported EPUB survives reload', await page.locator('.book-item').count() === 1)
  await page.getByLabel('选择 EPUB 文件').setInputFiles(new URL('../public/demo.epub', import.meta.url).pathname)
  await page.getByRole('status').waitFor()
  check('Duplicate EPUB import preserves one book', (await dbBooks()).length === 1)
  await page.locator('.book-item').click()
  await page.getByRole('heading', { name: '把时间留给阅读' }).waitFor()
  await page.getByRole('button', { name: '切换目录' }).click()
  await page.locator('.chapter-list').getByRole('button').nth(1).click()
  await page.getByRole('heading', { name: '在信息之间留白' }).waitFor()
  // Allow the reader's two-frame chapter layout/position restoration to finish.
  await page.waitForTimeout(250)
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight * .55))
  await page.waitForTimeout(650)
  stored = await dbBooks()
  check('EPUB reading chapter and progress are saved', stored[0].chapter === 1 && stored[0].offset > .1 && stored[0].progress > .33)
  await page.reload({ waitUntil: 'networkidle' }); await ready()
  await page.getByRole('heading', { name: '在信息之间留白' }).waitFor()
  await page.waitForTimeout(200)
  check('EPUB chapter and scroll position restore after reload', await page.evaluate(() => scrollY > 100))
  await shot('05-epub-reader.png')
  await page.getByRole('button', { name: '书架', exact: true }).click()
  await page.locator('.book-item').waitFor()
  await page.waitForTimeout(150)
  await shot('03-bookshelf.png')
  await page.getByRole('link', { name: '摘录', exact: true }).click()
  await page.locator('.excerpt-card').waitFor()
  check('Saved article excerpt is listed with origin', await page.locator('.excerpt-card').count() === 1)
  await shot('04-excerpts.png')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出摘录为 Markdown' }).click()
  check('Excerpts export as Markdown', (await download).suggestedFilename().endsWith('.md'))
  await page.getByRole('button', { name: '切换深色' }).click()
  check('Dark mode applies canonical CDS surface', await page.evaluate(() => getComputedStyle(document.body).backgroundColor === 'rgb(11, 11, 11)'))
  await shot('06-dark.png')
  await page.getByRole('button', { name: '切换浅色' }).click()
  await page.getByRole('link', { name: '订阅', exact: true }).click()
  await page.getByRole('button', { name: '订阅与数据状态' }).click()
  check('Source status dialog opens', await page.locator('dialog').evaluate(node => node.open))
  await page.keyboard.press('Escape')
  check('Source status dialog closes with Escape', await page.locator('dialog').evaluate(node => !node.open))
  await page.setViewportSize({ width: 1440, height: 900 })
  check('Desktop feed has no horizontal overflow', await noOverflow())
  await shot('07-desktop.png')
  await page.setViewportSize({ width: 768, height: 1024 })
  check('Tablet feed has no horizontal overflow', await noOverflow())
  await shot('08-tablet.png')
  await page.setViewportSize({ width: 320, height: 740 })
  check('Narrow 320px feed has no horizontal overflow', await noOverflow())
  await page.setViewportSize({ width: 390, height: 844 })
  await context.setOffline(true)
  await page.getByRole('button', { name: '重新读取订阅' }).click()
  await page.getByText('正在阅读离线缓存').waitFor()
  check('Feed falls back to cached winners when offline', await page.locator('.article-card').count() === feed.articles.length)
  await context.setOffline(false)
  // Controlled body states exercise empty/whitespace content and the body alias
  // without changing the real feed or its cached content.
  const edgeContext = await browser.newContext({ viewport: { width: 390, height: 844 } })
  const edge = await edgeContext.newPage()
  edge.on('pageerror', error => errors.push(error.message))
  let edgeArticle = { ...feed.articles[0], content: ' \n ' }
  await edge.route('**/data/articles.json', route => route.fulfill({ json: { ...feed, articles: [edgeArticle] } }))
  await edge.route('**/rest/v1/**', route => {
    const table = new URL(route.request().url()).pathname.split('/').at(-1)
    return route.fulfill({ json: table === 'sources' ? feed.sources : table === 'clusters'
      ? [{ id: edgeArticle.cluster_id, selection_mode: feed.selection_mode }] : [edgeArticle] })
  })
  await edge.goto(base, { waitUntil: 'networkidle' })
  check('Whitespace-only body is labeled pending in list', (await edge.locator('.article-kind').innerText()).includes('正文待同步'))
  await edge.locator('.article-link').click()
  await edge.getByRole('heading', { name: '正文尚未同步' }).waitFor()
  check('Whitespace-only body shows a clear empty state', await edge.getByRole('heading', { name: '正文尚未同步' }).isVisible() && await edge.locator('.reading-body').count() === 0)
  check('Missing body keeps summary separate and labeled', await edge.locator('.summary-notice h2').innerText() === '来源摘要' && await edge.locator('.summary-notice p').innerText() === edgeArticle.summary)
  await edge.screenshot({ path: `${output}09-body-pending.png` })
  edgeArticle = { ...edgeArticle, summary: '' }
  await edge.reload({ waitUntil: 'networkidle' })
  check('Missing body and summary produce no invented prose', await edge.locator('.body-empty').isVisible() && await edge.locator('.summary-notice, .reading-body, .excerpt-action').count() === 0)
  edgeArticle = { ...edgeArticle, body: bodyArticle.content }
  await edge.reload({ waitUntil: 'networkidle' })
  check('Body alias renders inline when content is blank', await edge.locator('.reading-body').innerText() === bodyArticle.content.trim())
  edgeArticle = { ...edgeArticle, content: 'Primary content paragraph.\n\nAnother primary paragraph.' }
  await edge.reload({ waitUntil: 'networkidle' })
  check('Content field takes precedence over body alias', await edge.locator('.reading-body').innerText() === edgeArticle.content)
  await edgeContext.close()
  check('No uncaught browser errors', errors.length === 0)
  await writeFile(`${output}checks.json`, JSON.stringify({ passed: checks.length, checks, browser_errors: errors, feed: { input: feed.input_count, winners: feed.cluster_count, mode: feed.selection_mode }, tested_at: new Date().toISOString() }, null, 2))
  console.log(`PASS: ${checks.length} browser and data checks; screenshots saved to ${output}`)
} finally { await browser.close() }
